const mkQ = (
  id: string,
  text: string,
  options: { label: string; text: string }[],
  correctIndex: number,
  explanation: string,
  topic: string,
  difficulty: Question['difficulty'],
  sourceReference?: string,
): Question => ({
  id,
  type: 'mcq',
  text,
  options: options.map((o, i) => ({
    id: `${id}_opt${i}`,
    label: o.label,
    text: o.text,
  })),
  correctOptionId: `${id}_opt${correctIndex}`,
  explanation,
  topic,
  difficulty,
  sourceReference,
});

